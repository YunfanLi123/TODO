#: 审计只查**规则自己的可执行文本**。
#:
#: ``source.quoted`` 与 rationale 里的「原文前提 / 原文结果」是**逐字引用**，
#: 按项目约定必须原样保留（那是给复核用的：让人能看到原文到底写了什么，
#: 以及我们把它改成了什么）。所以引用里的旧词**不算命中**。
OPERATIVE_FIELDS = ("title", "premise", "action", "outcome",
                     "deviation_hint", "hint")


def apply(text: str) -> str:
    """把已移除的机制换成当前版本真实存在的机制。"""
    if not text:
        return ""
    out = text
    for wrong, right in MECHANIC_FIXES.items():
        if wrong in out:
            out = out.replace(wrong, right)
    return out


def audit(text: str) -> List[str]:
    """这段文字里还提到了哪些**已移除**的机制。"""
    if not text:
        return []
    return sorted({m for m in REMOVED_MECHANICS if m in text})


def audit_rules(rules) -> List[Tuple[str, str, str]]:
    """审计一批规则：返回 ``(规则 id, 命中的机制, 标题)``。

    只看**可执行文本**，不看引用 —— 引用里留着原文是故意的。
    """
    out: List[Tuple[str, str, str]] = []
    for r in rules or []:
        blob = "\n".join(str(r.get(f, "") or "") for f in OPERATIVE_FIELDS)
        for m in audit(blob):
            out.append((r.get("id", ""), m, r.get("title", "")[:40]))
    return out


def revised_rules(rules) -> List[Tuple[str, str]]:
    """哪些规则**按当前版本改过**（引用里是旧机制，可执行文本里已经没有了）。

    报出来是为了让人知道：这条不是原文照抄，是按当前版本修订过的。
    """
    out: List[Tuple[str, str]] = []
    for r in rules or []:
        quoted = json.dumps(r.get("source") or {}, ensure_ascii=False)
        quoted += "原文前提：" + str(r.get("rationale") or "")
        if not audit(quoted):
            continue
        blob = "\n".join(str(r.get(f, "") or "") for f in OPERATIVE_FIELDS)
        if not audit(blob):
            out.append((r.get("id", ""), r.get("title", "")[:40]))
    return out


#: 当前版本河道目标刷新的分钟（空间之灵 2、暴君/主宰 4、暗影 10、风暴 20）。
OBJECTIVE_MINUTES = (2, 4, 10, 20)


def _time_window(rule) -> Optional[Tuple[int, int]]:
    """规则的时间窗（分钟）。认不出来返回 None。"""
    trig = rule.get("trigger") or {}
    for cond in list(trig.get("all") or []) + list(trig.get("any") or []):
        if cond.get("fact") != "time_min":
            continue
        val = cond.get("value")
        if isinstance(val, (list, tuple)) and len(val) == 2:
            return int(val[0]), int(val[1])
    return None


def needs_review(rules) -> List[Tuple[str, str, str]]:
    """原文提到河道目标、但时间窗里当前版本没有目标的规则。

    返回 ``(规则 id, 时间窗文字, 标题)``。这些规则不是改词能救的 ——
    它们的决策对象在当前版本已经不在那个时间点了，要人来定。
    """
    out: List[Tuple[str, str, str]] = []
    for r in rules or []:
        quoted = json.dumps(r.get("source") or {}, ensure_ascii=False)
        if not audit(quoted):
            continue
        win = _time_window(r)
        if win is None:
            continue
        lo, hi = win
        if any(lo <= m <= hi for m in OBJECTIVE_MINUTES):
            continue
        out.append((r.get("id", ""), f"{lo}~{hi} 分钟",
                    r.get("title", "")[:40]))
    return out
