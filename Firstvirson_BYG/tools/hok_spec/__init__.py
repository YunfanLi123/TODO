"""S45 决策树 -> 操作模式库的映射表。

一个模块一条分路（``tools/hok_spec/<lane>.py``），每个模块导出：

``LANE``
    分路编码（``jungle`` / ``mid`` / ``side`` / ``carry`` / ``roam``）。

``RULES``
    规则列表。每条对应攻略里的一个**分支组**（分支或合并后的分支）。

``SKIPPED``
    明确**不入库**的分支，附理由。生成器会检查攻略里每条分支都有归宿 ——
    漏写一条就报错，否则「攻略里明明写了，库里却查不到」这件事没人会发现。

一条规则的字段
--------------
``node``
    节点时间标签，和解析出来的一致（``"0:00"`` / ``"12:00"``）。

``key``
    分支标识 = 前提链用 ``" / "`` 连起来。嵌套分支写全路径，
    例如 ``"被对方二级抓中 / 血量低于一半"``。

``merge``
    可选。合并进来的其它分支前提（同一个节点内）。
    合并的判据见下面的「决策程序」。

``title``
    模式标题，给人看。

``expect``
    ``{"fact": 动作事实, "values": [取值, ...]}``。取值必须来自王者动作词表，
    否则标注页勾不出来，这条规则就永远判不出「做到了」。

``subject``
    可选。**适用时机**：玩家在这一帧做了这些动作时，这条规则才适用。
    典型用法是「取舍型」规则 —— 玩家在打资源 / 在打团时才判他该不该打，
    玩家在补刀推线时不算他做错。

``scope``
    ``"at_least_once"``（默认推荐）= 这一段里做到过一次就算整段做到；
    不填就是 ``"per_frame"``（每一个适用的时刻都该做）。

``extra`` / ``guards``
    额外的触发条件 / 护栏，写进 ``trigger.all`` / ``trigger.none``。
    只能用**标量事实**（``position`` / ``matchup`` / ``gold_diff`` /
    ``kill_diff`` / ``tower_diff`` / ``has_ult_ready`` / ``pressure``），
    不能用动作事实 —— 用动作事实做护栏会和同一格里的期望撞车，
    玩家会被两条模式同时指控。

``why``
    可选。补充说明（为什么这样判、哪些分支合并了）。
    原文的前提与后果会自动附在前面。

``hint``
    可选。偏离时给玩家的改法。默认取原文动作。

决策程序
--------
1. 读每条分支的**前提**和**动作**，分开看。
2. 前提里能写成标量事实的（敌方减员 → ``kill_diff``、己方落后 → ``gold_diff``、
   对位优劣 → ``matchup``），单独成条，把条件写进 ``extra``。
3. 前提判不了的（对方开野色、暴君倒计时、控制交没交、队友位置），
   和同一节点里其它分支**按「可接受动作集合」合并**：
   集合有交集就合并，``expect`` 取并集，并在 ``why`` 里说明合并了哪几条。
4. 动作里只有一部分能判定时（惩击时机、装备、喊话、指挥），
   判不了的部分写进 ``hint`` / ``why``；整条都判不了 → 放进 ``SKIPPED`` 并写明理由。
5. 同一个节点里两条规则若期望**同一动作事实**且取值不重叠，
   必须用 ``extra`` / ``guards`` 把它们互斥开（生成器会检查）；
   互斥不开就合并。
6. ``subject`` 要比 ``expect`` **宽**：它圈的是「这件事发生在哪一类操作里」，
   比 expect 宽才有判断力（宽到和 expect 一样就等于没判）。
7. 严重度：``high`` = 关键取舍（开不开团、控不控龙、什么时候转线）；
   ``medium`` = 节奏与效率（推塔顺序、视野覆盖、刷野效率）。
"""

