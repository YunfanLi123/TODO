"""**《王者荣耀》的界面常识** —— 给观察者模型当背景知识。

为什么要有它
------------
模型看王者画面时，如果没有游戏常识，会把**界面元素当成画面内容**。

2026-11-03 实测（``hok-video-372808da845d``）：在技能键的裁图上，
模型把**冷却倒计时「06」**当成了「红金色环形徽记」这个美术特征，
还照着它去匹配英雄 —— 于是认成了「杨玉环」。

（那是静态裁图链的病，视频链已经不走它了。但**常识确实缺**：
冷却数字、技能类型白字、「强化」键、地形与资源 —— 这些不讲，
模型就只能瞎猜。）

所以先把「**这块画面上有什么、分别是什么意思**」讲清楚，再让它干活。

放在哪
----
这是**背景知识**，不是任务指令 —— 所以各层（看整局 / 认英雄 / 对照检查）
把本模块的内容拼在**自己那套任务规则前面**：

* 任务规则在前、常识在后 → 最后的「只输出那个 JSON」离输出最近；
* 常识不写死英雄名单 —— 那是「从词表里挑名字」的老路
  （整帧 + 130 个英雄名 = 猜，实测答出过上官婉儿 / 云中君 / 澜）。
  模型认识这个游戏；要做的是让它**看懂界面**，不是给它一份名单。
"""

from __future__ import annotations

#: 《王者荣耀》的界面与玩法常识。
GAME_KNOWLEDGE = """\
【这是什么游戏】
《王者荣耀》—— 5v5 对抗的手机 MOBA，地图叫「王者峡谷」。
一局的流程：选人(BP) → 加载 → 对局 → 结算。
录屏来自**玩家自己的手机**，所以画面右下角是**这个玩家**的操作区。

【画面布局（横屏）】
- 左上角：**小地图**（峡谷俯瞰图）。上面有蓝色/红色的塔与英雄标记、
  中间那条**河道**、两侧**野区**（蓝 buff、红 buff、小野怪）、
  河道下方的**暴君坑**、上方的**主宰坑**。小地图上的圆圈**未必**是玩家
  （观战画面里它可能一直不动）—— 别拿它当玩家位置。
- 顶栏正中：双方**击杀数**、**局内时间 MM:SS**、经济差、信号。
  顶栏两端是双方的英雄头像（阵亡时头像上会有复活倒计时）。
- 左下角：虚拟摇杆。画面下方偏中间：回城的蓝色圆盘、商店/出装的圆圈。
- **右下角：技能区**（认英雄最要紧的地方，见下）。

【右下角技能区怎么读】
- **最大那个圆键**（最右下角）= **普攻键**。
- 普攻键左上方是一排圆键 = 各个**技能键**。**别去数「1技能/2技能/大招」**
  —— 实测这套界面是**四个键**（伤害、回复、控制、强化），键下的白字
  直接写着它的**类型**；靠位置猜是哪个技能会猜错。
- 每个技能键的**下半部压着一行白字** = **技能类型标签**
  （实测出现过的：伤害、回复、控制、强化；也可能是位移、护盾、治疗、召唤，
  以及眩晕、沉默、减速、击飞、击退等）。那是**画面上印着的字**，
  能看清就直接读出来 —— **这是最可靠的画面证据**。
- 技能键**圆圈中央的大数字 = 冷却倒计时**（还有几秒能用），
  **它不是美术**。数字盖在图标上的时候图标看不清 —— 这时要说明
  「被冷却数字挡住了」，**不要把数字当成图案特征**去认英雄。
  （2026-11-03 实测踩过：把冷却数字「06」当成了「红金色环形徽记」这个
  美术特征，然后照着它认成了杨玉环。）
- 普攻键旁边那一排小圆键 = **召唤师技能**（闪现=黄色靴子、治疗=十字、
  干扰=剪刀、惩击=拳套）与**回城 / 恢复**。
- 写着「**强化**」的键 = 该英雄的**形态键**（人形态 ↔ 另一种形态）。
  **这个键上常常就是该英雄的标志物**（比如一颗虎头）。

【选人(BP)界面 —— **这里印的大多不是英雄名**】
- 左侧竖着 5 行 = 本队 5 个玩家，**金色高亮的那一行是录屏的人自己**；
  别的行是队友。
- 每行印着：**头像 + 玩家昵称 + 分路（对抗路/中路/游走…）+「预选」状态**。
  ⚠️ **英雄名通常不印在这里**（2026-11-13 逐帧核对过那一局的选人界面）。
- 右侧是一张**候选英雄网格**，网格里每个英雄下面印着名字 ——
  那是「可以选谁」的清单，**不是「谁选了谁」**。
  鼠标停住时弹出的**英雄资料卡**也印名字（角色、特长），
  同样**不代表玩家选的就是它**。
- ⚠️ **「预选」不等于「最后选的那个」**：倒计时最后一秒会被抢，
  预选的那位可能临了被换掉。
- 结论：**选人界面读不出「玩家自己的英雄」**这件事要照实说（写 null），
  不要拿网格里、资料卡里、或者排在那里的某个名字去顶。
  它的价值是**禁用名单**（被禁的英雄不可能被选上）。

【战绩面板（局内打开的那张「战绩」大表）—— **英雄名印在这里**】
- 一局里玩家常会点开「战绩」面板：左右两列各 5 行，每行印着
  **英雄名 + 昵称 + K/D/A + 经济 + 装备**。
- **自己那一行是红底/高亮**（录屏的人自己）。
- 这是整局里**最靠得住的英雄名来源**：名字是游戏自己印的字。
  看到这张表就照抄你自己那一行印着的英雄名；看不到就写 null。
- 表头那行还有双方总击杀数；每一行的中间三个数字是
  **击杀 / 死亡 / 助攻** —— 你自己的死亡次数就在那儿，
  它比「凭记忆数」准得多。

【加载界面 —— 10 个英雄的长相都在这儿】
- 上下两排共 10 张**英雄立绘卡**，卡下方印着**该玩家的昵称**，
  卡上是那个玩家的英雄立绘 —— **这里最能看清每个英雄长什么样**。
- ⚠️ **卡上一般不印英雄的名字**（印的是**皮肤名**和昵称）；
  少数皮肤名里带英雄名（如「怪盗基德 马可波罗」），
  但那是皮肤文案，**不能当成可靠的读法**。
- 上下两排分别是哪一方，要靠别处的信息判断（哪一排里有玩家自己的昵称）。

【认英雄的纪律（踩过很多次）】
- **优先读画面上印着的字**；**读不到就说不知道**（写 null）。
- **不要靠头像/立绘去猜英雄名字**：2026-11-03 实测 9 次，
  局内技能图标、加载页立绘、跨片段对照，**没有一次猜对**，
  而游戏自己印着的名字一直都对。
- **整帧分辨率下的小字很难看清**（加载页卡下的昵称、
  BP 行里印的英雄名）。看不清就**直说看不清**，不要编一个像的名字 ——
  编出来的名字会被当成结论，然后整套打法都套到别人身上。

【谁是玩家自己】
- 玩家自己 = **操作区（右下角）**对应的那个人：技能键随着ta的操作亮起/变灰；
  画面中央被跟随、头顶带名字条的那个也是ta。
- 画面里还有队友和敌人：**队友血条绿、敌人血条红**。
  **认玩家自己的英雄时不要把场上别人算进去**（实测踩过：把**队友**的英雄
  当成了玩家，于是整套攻略都按别人来挑）。
- 英雄名用《王者荣耀》的官方中文名。**认不出就写 null**，
  不要挑一个「看着像」的英雄 —— 认错一个英雄，整套打法都会套到别人身上。

【地图与资源 —— **只写当前版本真的有的东西**】
- **河道**：中间那条河，把地图分成两半，也是打野与支援最常出现的地方。
- **野区**：蓝 buff、红 buff、以及小野怪（鸟、猪、蜥蜴）；
  打野在开局会去蓝开或红开。
- **暴君 / 暗影暴君**（河道下方）与**主宰 / 暗影主宰**（上方）——
  大龙（主宰）是决定后期的一波团。
- **防御塔**：沿边路与中路分布；推塔、守塔、塔下残血是常见的画面状态。
- **空间之灵**：对抗路传送阵那一只，2:00 刷，只有一次。
- ⚠️ **「河道之灵 / 河道精灵 / 河蟹 / 河道蟹」在这个版本已经不存在了**
  （S36 起删掉：中路彻底没有，对抗路换成空间之灵）。
  **不要**在叙述里写「刷河道蟹」「抢河道之灵」——
  那是旧版本的词，写出来就是编的。河道里没有可打的资源目标，
  河道里发生的是**遭遇战、做视野、蹲草丛**。
  拿不准那个东西叫什么，就按画面说「在河道打了一波」。

【结算画面 —— 与「水晶爆裂」不是一回事】
- 结算画面是**单独一屏**：写着「胜利 / 失败」、双方 K/D/A 与战绩。
- **基地水晶被打爆只是画面效果**，它出现在结算画面**之前**
  （录屏常常在结算页出来前就结束了）。
- 所以：**只有真的看到写着「胜利」「失败」的那一屏，才说「结算画面」**；
  看到水晶爆裂只能说「水晶被打爆」，**不要**说「结算画面明确显示失败」。

【分路（位置）】
- **对抗路**（战士）、**发育路**（射手）、**中路**（法师）、**打野**、**游走**（辅助）。
- 画面线索：打野出现在野区与河道、打野怪；发育路在边路补刀farm；
  中路在中央兵线；游走跟着打野、在草丛与河道做视野。
- 标「这一段玩家在哪条路」时只用这几个词：**上路 / 中路 / 下路 / 发育路 / 野区**
  （看不出就写 unknown）。**上路与下路都属对抗路**，但要分开标 ——
  玩家说的是「我走上路」，报告只写「对抗路」他会觉得没说清。

【位置怎么说 —— 赛事解说的说法】
解说报位置用的是下面这些词。**照着用**，别写成「第一座防御塔附近」
「河道一侧」这种说明书式的写法：
- **河道**：河道草丛、河道入口、河道口（**这个版本没有「河道蟹」**）；
- **龙坑**：龙坑（河道下方那个坑）、暴君坑、主宰坑；
- **边路**：一塔前、塔下、塔后、二塔前、对线区、兵线交汇处；
- **野区**：红buff、红怪、蓝buff、蓝怪、鸟窝、猪、蜥蜴、野区入口；
- **中路**：中路一塔前、中路河道口、高地塔下、兵线；
- **其它**：泉水、回城、基地、敌方高地。

【解说腔怎么写】
解说讲一段的套路是：**位置 + 动作 + 结果**，短句，带判断，不复述画面。
- ✗ 「玩家在中路河道附近遭遇敌方英雄，用远程尖刺状弹道攻击敌人，
  并与身后的中路队友一起持续输出。」（复述画面、没结果、没判断）
- ✓ 「中路河道打起来，他在后手远程压血量，对面打野绕侧面包夹，
  闪现交了才撤走。」
- ✓ 「上路一塔前跟对面换血，他半血对面满血，这波血亏。」
- ✓ 「龙坑开团，他闪现进去收掉对面打野，一换一，血量见底。」
常用赛事术语：换血、拉扯、压线、抢线权、开团、反蹲、收割、支援、游走、
越塔、包抄、一换一、单杀、先手、后手、消耗、对拼、逼位置、控龙、推塔。

【时间】
- 顶栏正中的 MM:SS 是**局内时间**。
- **选人、加载、结算都不算「对局中」** —— 进入战场画面那一刻才是开局。
"""

#: 各层拼提示词时用的接口。
def knowledge_for(game: str = "hok") -> str:
    """某个游戏的界面常识。别的游戏目前没有，返回空串。"""
    key = (game or "").strip().lower()
    if key in ("hok", "kings", "honor_of_kings", "wangzhe"):
        return GAME_KNOWLEDGE
    return ""
