"""全局动作描述的提示词（重写版）。

这一层只干两件事：
1. **先认人** —— 认出玩家自己操作的是哪个英雄，后面只描述这个角色；
2. **按三段描述** —— 前期 0-5、中期 5-10、后期 10-结束（局内时间），
   每段找四类关键时刻：自己阵亡、丢本路塔、击杀、拆塔。

为什么把「认人」放在最前：模型看整局时只要把注意力放错人
（队友/对手），后面四类事件的叙述就全落在别人身上 —— 报告会拿别人的
打法去指责玩家。所以先让它说清「凭什么认定是他」，再让它干活。

提示词只描述、不判对错；判定在 app/harness 那一层。
"""

from __future__ import annotations

from typing import List, Sequence

#: 三段的局内时间边界（分钟）。后期没有上界。
STAGES = (("early", 0.0, 5.0), ("mid", 5.0, 10.0), ("late", 10.0, None))

#: 每段要找的四类事件（丢塔本版不输出，不在其列）。
EVENT_TYPES = ("death", "kill", "tower_taken", "dragon")

#: 分路码 -> 中文（注入「已知身份」时用）。
POSITION_CN = {"side": "对抗路", "carry": "发育路", "mid": "中路",
               "jungle": "打野", "roam": "游走", "unknown": "分路未知"}


def _identity_block(hero: str = "", position: str = "") -> List[str]:
    """「已知身份」那一段。

    玩家上传前自己填了英雄/分路时，把它写死在提示里：模型不必再猜，
    也**不允许**把注意力放到队友身上。没填就什么都不加（走老路）。
    """
    hero = (hero or "").strip()
    position = (position or "").strip()
    if not hero and not position:
        return []
    bits = []
    if hero:
        bits.append("英雄「%s」" % hero)
    if position:
        bits.append("分路「%s」" % POSITION_CN.get(position, position))
    lines = ["【已知身份】玩家自己用的是" + "，".join(bits) + "。"]
    if hero:
        lines.append("整段录像**只描述这个角色**；hero 照抄这个值，"
                     "hero_evidence 写「玩家赛前填写」。不要改写成别的英雄。")
        lines.append("叙述里一律用「%s」称呼玩家，**禁止**写「他」「玩家」" 
                     "「镜头主人」。" % hero)
    else:
        lines.append("整段录像**只描述这个角色**（以右下角操作区为准）。")
    lines.append("敌方阵营一律写「敌方英雄」，队友一律写「队友」；"
                 "队友的击杀/推塔不记成玩家的事件。")
    lines.append("")
    return lines

_SYSTEM = """【这一层的活】
你是《王者荣耀》对局复盘助手。你会拿到一段完整对局录像。
你只做两件事：
1. 先认准「玩家在操作哪个英雄」；
2. 按局内时间的前期 / 中期 / 后期，把四类关键时刻的过程用文字讲清楚。

【第一步：先认人（必须先做；这一步错了，后面全落到别人身上）】
- **玩家自己** = 右下角操作区对应的那个角色：技能键随着他的操作亮起/变灰，
  镜头跟着他走，脚下有名字条。**队友血条是绿色、敌方是红色，都不算玩家。**
- 认准之后，**整段录像只描述这个角色在做什么**。
- 英雄名**只采信画面上印着的字**：局内战绩面板里**红底/高亮的那一行**
  （5 行里只有那一行是玩家自己），或聊天框里的「昵称(英雄名)」。
  读不到就写 null —— **不要按外形/头像猜**（猜错一个，整局都在讲别人）。
- 在 hero_evidence 里写清依据（例：「右下角技能区亮的是他的技能，镜头一直跟着他」）。

【怎么写人物（必须严格遵守）】
- 玩家一律用**英雄名**称呼（例：「敖隐绕后」）。**禁止**写「他」「玩家」
  「镜头主人」来指玩家；英雄名实在读不到，才写「玩家」。
- **敌方阵营的角色一律写「敌方英雄」**。禁止写「红名英雄」「红方英雄」
  「蓝方英雄」「对面射手」「红方」「蓝方」「对面」这类说法，
  **也不要写敌方英雄的具体名字**（如「孙悟空」）—— 一律写「敌方英雄」。
- **队友一律写「队友」**。队友的击杀、推塔**不算玩家的**：
  **不要**记成 kill / tower_taken 事件；叙述里可以提一句「队友击杀」，
  但事件本身不记。只有玩家自己完成的才记。
- 不要用**颜色**指代阵营（红色 / 蓝色 / 红名 / 蓝名），
  也不要写「红色血条」这类颜色标签 —— 一律用「敌方英雄」「队友」「敖隐」。
- **我方一律写「我方」**，敌方一律写「敌方英雄」；**不要写「红方」「蓝方」**。

【第二步：按局内时间分三段】
以**顶栏正中的局内时刻 MM:SS** 为准：
- 前期：0:00 – 5:00
- 中期：5:00 – 10:00
- 后期：10:00 – 对局结束

每一段里找下面四类事件（**有就写，没有就写空数组 []，不许编**）：
1. death        玩家自己阵亡：取死前 3 秒到死后 3 秒的过程；
2. kill         **玩家自己**击杀敌方英雄；
3. tower_taken  **玩家自己**摧毁敌方防御塔 —— 只有**同时**看到「玩家在塔前」
                **且「塔爆」**才写，只看到「已摧毁」提示不算；
4. dragon       玩家击杀龙 —— 只有**同时**看到「玩家在龙前」**且「龙死」**才写。

玩家阵亡、等复活的那段时间里，队友完成的击杀/推塔**不算玩家的**，不要记。

每条事件都要写：
- clock：**局内时刻 MM:SS（必填）**，stage 必须与它一致；
  看不清就写 null，并且不要硬塞进某一段；
- t / t_end：录像里的秒数（内部定位用，**不要写进叙述**）；
- frames：你判断这条事件所依据的那几帧在录像里的秒数（2~5 个，按先后）；
- lane / where：地点写**「归属 + 路」** —— 己方 / 敌方 + 上路 / 中路 / 下路；
  例：**「敌方上路」「己方中路」「上路」**；
- 河道、野区不写归属，只写「河道」或「野区」；
- 不知道归属就只写路名（「上路」）；不知道哪条路就留空，**不要编**；
- 不要写「野区防御塔前」「中路一塔」这类组合或编号；
- narrative：把过程讲清楚 —— 玩家（用英雄名）在做什么、敌方英雄怎么反应、
  结果如何；用职业赛事解说的短句、带判断（换血、开团、包抄、一换一）：
  「敖隐在后手压血量，敌方打野绕后包夹，闪现交了才撤」。
  **只写画面里看得到的**；**叙述里不要写任何时间数字**
  （局内时间由报告统一标注），也不要写录像秒；看不清就写「看不清」，不要补。
- 死亡事件另写：at（死在哪）、cause（怎么死的）、fault（玩家哪一步出的问题，
  看不出写 unknown）。

【纪律】
0. **禁止写具体技能**：不要写「大招」「一技能/二技能」「位移」「闪现」「控制技能」
   「技能名」这类 —— 你看不清技能，只写「输出 / 攻击 / 换血 / 走位」。
1. 只写你在画面里看见的，不猜、不编、不套模板。
2. 队友/敌方英雄的操作**不写成本人**；阵亡后镜头切给队友的那几秒要说清「队友在打」。
3. 不写这个版本没有的东西；英雄名、击杀数看不清就不要编。
4. 叙述里不写时间数字；clock 只填你真的从顶栏读到的时刻，读不准就写 null。
5. **只输出那一个 JSON 对象**，不要写分析过程、不要写前后说明。
"""

SYSTEM_PROMPT = _SYSTEM

#: 抽帧那条路：在系统提示后面补一段「这次是抽帧」的说明。
FRAMES_SYSTEM_PROMPT = _SYSTEM + """
【⚠️ 这次给你的是**抽出来的画面**，不是连续视频】
整局的连续视频发不过来，所以给的是按时间抽出的画面：
每一张都标着它在录像里的秒数，相邻两张可能隔 1~5 秒。因此：
1. **只写这几张里真的看得到的事**；两张之间的过程看不到就别补。
2. 事件时间只能用**标出来的那些秒数**（或相邻两张之间），不要写出这一批范围以外。
3. 拿不准的英雄名、击杀数照旧写 null / unknown —— 抽帧本身就是信息不全，
   老实说比编一段顺畅的解说有用。
"""

_JSON_SHAPE = (
    '{"hero": "玩家操控的英雄官方中文名 或 null", '
    '"hero_evidence": "你凭什么认定是他", '
    '"match_start": 对局开始的录像秒数 或 null, '
    '"position": "主要打哪条线 jungle/mid/side/carry/roam/unknown", '
    '"result": "win|lose|unknown", '
    '"stages": ['
    '{"stage": "early", "events": ['
    '{"clock": "局内 MM:SS（必填）", '
    '"t": 录像起始秒, "t_end": 录像结束秒, '
    '"type": "death|kill|tower_taken|dragon", '
    '"frames": [依据帧的录像秒], '
    '"lane": "上路|中路|下路|发育路|野区|unknown", '
    '"where": "具体地点", '
    '"narrative": "这一下发生了什么（局内时刻 + 英雄名 + 敌方英雄/队友）", '
    '"at": "死在哪（仅 death）", '
    '"cause": "怎么死的（仅 death）", '
    '"fault": "哪一步出的问题（仅 death，看不出写 unknown）"}]}, '
    '{"stage": "mid", "events": [...]}, '
    '{"stage": "late", "events": [...]}]}'
)


def build_prompt(duration: float, hero: str = "",
                 position: str = "") -> str:
    """造「看整局录像」那一次的提问。

    hero / position 是玩家上传前自己填的；给了就以它为准（见 _identity_block）。
    """
    hero = (hero or "").strip()
    lines = _identity_block(hero, position)
    lines.append("这是整局录像，从第 0 秒到第 %.0f 秒。" % max(0.0, float(duration)))
    if hero:
        lines.append("玩家自己操作的是「%s」，不用再猜英雄。" % hero)
    else:
        lines.append("请先认出玩家自己操作的是哪个英雄"
                     "（在 hero_evidence 里写依据），")
    lines += [
        "再按前期 0-5 分钟、中期 5-10 分钟、后期 10 分钟以后三段，",
        "把四类关键时刻（自己阵亡 / 丢本路塔 / 击杀 / 拆塔）的过程讲清楚。",
        "只回答一个 JSON 对象：",
        _JSON_SHAPE,
    ]
    return "\n".join(lines)


def build_frames_prompt(lo: float, hi: float, times: Sequence[float],
                        index: int, total: int,
                        prev_summary: str = "",
                        hero: str = "", position: str = "") -> str:
    """造抽帧那条路某一批的提问。

    每张都标出它在原视频第几秒 —— 模型的时间判断全靠这些标签。
    hero / position 是玩家上传前自己填的（给了就写进提示）。
    """
    lines: List[str] = []
    lines.append("这是同一局《王者荣耀》录像里**第 %.0f ~ %.0f 秒**"
                 "（原视频时间）的画面，按时间顺序共 %d 张："
                 % (lo, hi, len(times)))
    for t in times:
        lines.append("  第 %.1f 秒" % float(t))
    lines.append("")
    lines.extend(_identity_block(hero, position))
    if index > 0 and prev_summary.strip():
        lines.append("上一批讲到：%s" % prev_summary.strip()[:200])
        lines.append("（只用来衔接，**不要重复**上一批已经写过的事。）")
        lines.append("")
    lines.append("**只讲这一批（第 %.0f ~ %.0f 秒）里发生的事**，"
                 "不要讲这一段以外的事。" % (lo, hi))
    lines.append("先认准玩家自己操作的是哪个英雄，再讲四类关键时刻"
                 "（自己阵亡 / 丢本路塔 / 击杀 / 拆塔）。")
    lines.append("只回答一个 JSON 对象（**只有第 1 批要填 match_start**，"
                 "其余批写 null）：")
    lines.append(_JSON_SHAPE)
    lines.append("")
    lines.append("要求：")
    lines.append("1. 事件时间只能取上面列出的秒数（或相邻两张之间），"
                 "不要写这一批范围以外的时间。")
    lines.append("2. 只写这几张画面里真的看得到的事；看不到的类别直接空着，不要编。")
    lines.append("3. 死亡只在看到玩家真的倒地/阵亡时写，并带上 at / cause / fault。")
    lines.append("4. 顶栏 MM:SS 能看清就填进 clock —— 对局起点靠它校准。")
    lines.append("5. ⚠️ hero 只在读出画面上的字时才填（战绩面板红底那一行、"
                 "或聊天框「昵称(英雄名)」）；读不到写 null，不要按外形猜。")
    return "\n".join(lines)
