#: 一句话最多这么长（进页面一行，太长就断）。
MAX_LEN = 220


def explain(*texts: str) -> str:
    """按动作里出现的关键词补一句「为什么有用」。补不出来就是空串。"""
    blob = " ".join(str(t or "") for t in texts)
    if not blob.strip():
        return ""
    for words, text in MECHANISMS:
        if any(word in blob for word in words):
            return text if len(text) <= MAX_LEN else text[:MAX_LEN] + "…"
    return ""


def matched(words: Sequence[str], *texts: str) -> List[str]:
    """这段文字命中了哪些关键词（排查用）。"""
    blob = " ".join(str(t or "") for t in texts)
    return [w for w in words if w in blob]
